// Writes include/cad_brep.h from src/layout.ts and include/cad_analysis.h from src/analysis-layout.ts:
// `node packages/cad-brep/gen/header.ts`. A test checks the committed headers are current, and compiles readers
// against them.

import { writeFileSync } from 'node:fs';
import * as A from '../src/analysis-layout.ts';
import { ANALYSIS_COLUMNS, ANALYSIS_HEADER_BYTES } from '../src/analysis.ts';
import { COLUMNS, HEADER_BYTES } from '../src/data.ts';
import * as L from '../src/layout.ts';
import { cEnum as enumOf, cHeader, named, wrap } from './common.ts';

function layouts(title: string, table: Record<string, { reals: string; ints: string }>): string[] {
  const out = wrap(`${title}, from a row's real and int offsets into its table's pools:`, ' * ');
  out[0] = `/*${out[0]!.slice(2)}`;
  for (const [kind, l] of Object.entries(table)) {
    out.push(...wrap(`${kind}: reals ${l.reals || 'none'}; ints ${l.ints || 'none'}.`, ' *   '));
  }
  out.push(' */', '');
  return out;
}

export function headerText(): string {
  return cHeader('cbr', 'CAD_BREP_H', { magic: L.MAGIC, columns: COLUMNS, headerBytes: HEADER_BYTES }, [
    '/* cad_brep.h: a cad-brep buffer (one part\'s B-rep) for C and C++ readers. Generated by',
    ' * packages/cad-brep/gen/header.ts from packages/cad-brep/src/layout.ts, which documents every table and column;',
    ' * don\'t edit. The buffer: the magic, a uint32 column count, then per column (enum cbr_column) its byte offset',
    ' * and element count (uint32 each), then the columns, each 8-byte aligned. Little-endian; cbr_open assumes a',
    ' * little-endian host and a buffer that is itself 8-byte aligned (malloc\'s is). */',
  ], [
    ...enumOf('cbr_curve_kind', 'CBR_CURVE', L.CURVE_KIND),
    ...enumOf('cbr_surface_kind', 'CBR_SURFACE', L.SURFACE_KIND),
    ...enumOf('cbr_logical', 'CBR_LOGICAL', L.LOGICAL),
    ...enumOf('cbr_orientation', 'CBR_ORIENTATION', L.ORIENTATION),
    ...enumOf('cbr_loop_kind', 'CBR_LOOP', L.LOOP_KIND),
    ...enumOf('cbr_bound', 'CBR_BOUND', L.BOUND),
    ...enumOf('cbr_shell_kind', 'CBR_SHELL', L.SHELL_KIND),
    ...enumOf('cbr_shell_declared', 'CBR_SHELL_DECLARED', L.SHELL_DECLARED),
    ...enumOf('cbr_body_kind', 'CBR_BODY', L.BODY_KIND),
    ...enumOf('cbr_item_kind', 'CBR_ITEM', L.ITEM_KIND),
    ...enumOf('cbr_curve_form', 'CBR_CURVE_FORM', named(L.CURVE_FORMS)),
    ...enumOf('cbr_surface_form', 'CBR_SURFACE_FORM', named(L.SURFACE_FORMS)),
    ...enumOf('cbr_transition', 'CBR_TRANSITION', named(L.TRANSITIONS)),
    ...enumOf('cbr_trim_preference', 'CBR_TRIM', named(L.TRIM_PREFERENCES)),
    ...layouts('Curves (d the row\'s dim; a placement 9 reals in 3D: origin, axis, x direction; 4 in 2D: origin, x '
      + 'direction)', L.CURVE_LAYOUTS),
    ...layouts('Surfaces (a placement 9 reals)', L.SURFACE_LAYOUTS),
  ]);
}

export function analysisHeaderText(): string {
  return cHeader('cba', 'CAD_ANALYSIS_H', { magic: A.ANALYSIS_MAGIC, columns: ANALYSIS_COLUMNS,
    headerBytes: ANALYSIS_HEADER_BYTES }, [
    '/* cad_analysis.h: a cad-brep analysis buffer (what is derived from one model buffer, tied to it by the model\'s',
    ' * SHA-256) for C and C++ readers. Generated by packages/cad-brep/gen/header.ts from',
    ' * packages/cad-brep/src/analysis-layout.ts, which documents every table and column; don\'t edit. The format is',
    ' * cad_brep.h\'s (the magic, a uint32 column count, then per column, enum cba_column, its byte offset and',
    ' * element count, then the columns, each 8-byte aligned), and cba_open assumes what cbr_open does. A per-entity',
    ' * table (vertex, edge, coedge, face, surface, shell) is empty or has the model\'s rows; checking that, and the',
    ' * hash, is the caller\'s. */',
  ], [
    ...enumOf('cba_provenance', 'CBA_PROVENANCE', A.PROVENANCE),
    ...enumOf('cba_measure_trust', 'CBA_TRUST', A.MEASURE_TRUST),
    ...enumOf('cba_continuity', 'CBA_CONTINUITY', A.CONTINUITY),
    ...enumOf('cba_singularity', 'CBA_SINGULARITY', A.SINGULARITY),
    ...enumOf('cba_facing', 'CBA_FACING', A.FACING),
    ...enumOf('cba_facing_from', 'CBA_FACING_FROM', A.FACING_FROM),
    ...enumOf('cba_logical', 'CBA_LOGICAL', L.LOGICAL),
  ]);
}

if (import.meta.main) {
  for (const [file, text] of [['cad_brep.h', headerText()], ['cad_analysis.h', analysisHeaderText()]] as const) {
    const path = new URL(`../include/${file}`, import.meta.url);
    writeFileSync(path, text);
    console.log(`wrote ${path.pathname}`);
  }
}
