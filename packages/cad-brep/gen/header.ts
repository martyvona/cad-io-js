// Writes include/cad_brep.h from src/layout.ts: `node packages/cad-brep/gen/header.ts`. A test checks the committed
// header is current, and compiles a reader against it.

import { writeFileSync } from 'node:fs';
import { COLUMNS, HEADER_BYTES } from '../src/data.ts';
import * as L from '../src/layout.ts';

const snake = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
const C_TYPES = { u8: 'uint8_t', i32: 'int32_t', u32: 'uint32_t', f64: 'double' } as const;

/** A comment's text word-wrapped to lines of at most 120 characters, each starting with `lead`. */
function wrap(text: string, lead: string): string[] {
  const lines: string[] = [];
  let line = lead;
  for (const w of text.split(/\s+/)) {
    if (line.length + 1 + w.length > 120 && line.trim() !== lead.trim()) {
      lines.push(line);
      line = lead;
    }
    line += (line === lead ? '' : ' ') + w;
  }
  lines.push(line);
  return lines;
}

function enumOf(name: string, prefix: string, table: Record<string, number>): string[] {
  return [`enum ${name} {`, ...Object.entries(table).map(([k, v]) => `  ${prefix}_${snake(k)} = ${v},`), '};', ''];
}

function namesOf(name: string, prefix: string, names: readonly string[]): string[] {
  return enumOf(name, prefix, Object.fromEntries(names.map((n, k) => [n, k])));
}

function layouts(title: string, table: Record<string, { reals: string; ints: string }>): string[] {
  const out = wrap(`${title}, from a row's real and int offsets into its table's pools:`, ' * ');
  out[0] = `/*${out[0]!.slice(2)}`;
  for (const [kind, l] of Object.entries(table)) {
    out.push(...wrap(`${kind}: reals ${l.reals || 'none'}; ints ${l.ints || 'none'}.`, ' *   '));
  }
  out.push(' */', '');
  return out;
}

export function headerText(): string {
  const out = [
    '/* cad_brep.h: a cad-brep buffer (one part\'s B-rep) for C and C++ readers. Generated by',
    ' * packages/cad-brep/gen/header.ts from packages/cad-brep/src/layout.ts, which documents every table and column;',
    ' * don\'t edit. The buffer: the magic, a uint32 column count, then per column (enum cbr_column) its byte offset',
    ' * and element count (uint32 each), then the columns, each 8-byte aligned. Little-endian; cbr_open assumes a',
    ' * little-endian host and a buffer that is itself 8-byte aligned (malloc\'s is). */',
    '#ifndef CAD_BREP_H',
    '#define CAD_BREP_H',
    '',
    '#include <stddef.h>',
    '#include <stdint.h>',
    '#include <string.h>',
    '',
    `#define CBR_MAGIC "${L.MAGIC}"`,
    `#define CBR_HEADER_BYTES ${HEADER_BYTES}`,
    '',
    '/* The columns in buffer order: table, column, element type and values per row. */',
    'enum cbr_column {',
    ...COLUMNS.map((c) => `  CBR_${snake(c.table)}_${snake(c.column)}, /* ${C_TYPES[c.type]} x ${c.width} */`),
    '  CBR_COLUMN_COUNT',
    '};',
    '',
    ...enumOf('cbr_curve_kind', 'CBR_CURVE', L.CURVE_KIND),
    ...enumOf('cbr_surface_kind', 'CBR_SURFACE', L.SURFACE_KIND),
    ...enumOf('cbr_logical', 'CBR_LOGICAL', L.LOGICAL),
    ...enumOf('cbr_orientation', 'CBR_ORIENTATION', L.ORIENTATION),
    ...enumOf('cbr_loop_kind', 'CBR_LOOP', L.LOOP_KIND),
    ...enumOf('cbr_bound', 'CBR_BOUND', L.BOUND),
    ...enumOf('cbr_shell_kind', 'CBR_SHELL', L.SHELL_KIND),
    ...enumOf('cbr_shell_declared', 'CBR_SHELL_DECLARED', L.SHELL_DECLARED),
    ...enumOf('cbr_body_kind', 'CBR_BODY', L.BODY_KIND),
    ...enumOf('cbr_item_kind', 'CBR_ITEM', L.ITEM_KIND),
    ...namesOf('cbr_curve_form', 'CBR_CURVE_FORM', L.CURVE_FORMS),
    ...namesOf('cbr_surface_form', 'CBR_SURFACE_FORM', L.SURFACE_FORMS),
    ...namesOf('cbr_transition', 'CBR_TRANSITION', L.TRANSITIONS),
    ...namesOf('cbr_trim_preference', 'CBR_TRIM', L.TRIM_PREFERENCES),
    ...layouts('Curves (d the row\'s dim; a placement 9 reals in 3D: origin, axis, x direction; 4 in 2D: origin, x '
      + 'direction)', L.CURVE_LAYOUTS),
    ...layouts('Surfaces (a placement 9 reals)', L.SURFACE_LAYOUTS),
    '/* One column: its values and their count (rows times its width). */',
    'typedef struct {',
    '  const void* data;',
    '  uint32_t count;',
    '} cbr_view;',
    '',
    '/* The columns of a buffer of `size` bytes into `views` (CBR_COLUMN_COUNT of them): 0, or -1 if it isn\'t one. */',
    'static inline int cbr_open(const uint8_t* buf, size_t size, cbr_view* views) {',
    '  static const uint8_t bytes[CBR_COLUMN_COUNT] = {',
    ...wrap(COLUMNS.map((c) => `${({ u8: 1, i32: 4, u32: 4, f64: 8 })[c.type]},`).join(' '), '    '),
    '  };',
    '  uint32_t n, k;',
    '  if (((uintptr_t)buf & 7) != 0 || size < CBR_HEADER_BYTES || memcmp(buf, CBR_MAGIC, 4) != 0) return -1;',
    '  memcpy(&n, buf + 4, 4);',
    '  if (n != CBR_COLUMN_COUNT) return -1;',
    '  for (k = 0; k < n; k++) {',
    '    uint32_t offset, count;',
    '    memcpy(&offset, buf + 8 + 8 * k, 4);',
    '    memcpy(&count, buf + 12 + 8 * k, 4);',
    '    if ((offset & 7) != 0 || offset < CBR_HEADER_BYTES || offset > size',
    '      || (uint64_t)count * bytes[k] > size - offset) return -1;',
    '    views[k].data = buf + offset;',
    '    views[k].count = count;',
    '  }',
    '  return 0;',
    '}',
    '',
    '#define CBR_U8(v) ((const uint8_t*)(v).data)',
    '#define CBR_I32(v) ((const int32_t*)(v).data)',
    '#define CBR_U32(v) ((const uint32_t*)(v).data)',
    '#define CBR_F64(v) ((const double*)(v).data)',
    '',
    '#endif',
    '',
  ];
  return out.join('\n');
}

if (import.meta.main) {
  const path = new URL('../include/cad_brep.h', import.meta.url);
  writeFileSync(path, headerText());
  console.log(`wrote ${path.pathname}`);
}
