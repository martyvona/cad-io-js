// Writes include/cad_brep.rs from src/layout.ts and include/cad_analysis.rs from src/analysis-layout.ts:
// `node packages/cad-brep/gen/rust.ts`. A test checks the committed modules are current, and compiles readers against
// them.

import { writeFileSync } from 'node:fs';
import * as A from '../src/analysis-layout.ts';
import { ANALYSIS_COLUMNS, ANALYSIS_HEADER_BYTES } from '../src/analysis.ts';
import { COLUMNS, HEADER_BYTES } from '../src/data.ts';
import * as L from '../src/layout.ts';
import { named, rustConsts as consts, rustModule, wrap } from './common.ts';

function layouts(title: string, table: Record<string, { reals: string; ints: string }>): string[] {
  const out = wrap(`${title}, from a row's real and int offsets into its table's pools:`, '//! ');
  for (const [kind, l] of Object.entries(table)) {
    out.push(...wrap(`${kind}: reals ${l.reals || 'none'}; ints ${l.ints || 'none'}.`, '//!   '));
  }
  return out;
}

export function rustText(): string {
  return rustModule('Brep', 'cad-brep buffer', { magic: L.MAGIC, columns: COLUMNS, headerBytes: HEADER_BYTES }, [
    '//! cad_brep.rs: a cad-brep buffer (one part\'s B-rep) for Rust readers. Generated by',
    '//! packages/cad-brep/gen/rust.ts from packages/cad-brep/src/layout.ts, which documents every table and column;',
    '//! don\'t edit. The buffer: the magic, a u32 column count, then per column its byte offset and element count',
    '//! (u32 each), then the columns, each 8-byte aligned. Little-endian. `Brep::open` copies the buffer (so it',
    '//! needn\'t be aligned) and checks its header; each column is then a slice of its type, by a method named for',
    '//! its table and column (`edge_curve`).',
    '//!',
    ...layouts('Curves (d the row\'s dim; a placement 9 reals in 3D: origin, axis, x direction; 4 in 2D: origin, x '
      + 'direction)', L.CURVE_LAYOUTS),
    '//!',
    ...layouts('Surfaces (a placement 9 reals)', L.SURFACE_LAYOUTS),
  ], [
    ...consts('curve_kind', 'u8', L.CURVE_KIND, 'Curve kinds (`curve_kind`).'),
    ...consts('surface_kind', 'u8', L.SURFACE_KIND, 'Surface kinds (`surface_kind`).'),
    ...consts('logical', 'i32', L.LOGICAL, 'Three-valued logicals, as the pools hold them.'),
    ...consts('orientation', 'u8', L.ORIENTATION, 'Coedge orientations (`coedge_orientation`).'),
    ...consts('loop_kind', 'u8', L.LOOP_KIND, 'Loop kinds (`loop_kind`).'),
    ...consts('bound', 'u8', L.BOUND, 'Loop bounds (`loop_bound`).'),
    ...consts('shell_kind', 'u8', L.SHELL_KIND, 'Shell kinds (`shell_kind`).'),
    ...consts('shell_declared', 'u8', L.SHELL_DECLARED, 'What sources declared shells (`shell_declared`).'),
    ...consts('body_kind', 'u8', L.BODY_KIND, 'Body kinds (`body_kind`).'),
    ...consts('item_kind', 'u8', L.ITEM_KIND, 'Item kinds (`item_kind`).'),
    ...consts('curve_form', 'i32', named(L.CURVE_FORMS), 'B-spline curve forms, as the pools hold them.'),
    ...consts('surface_form', 'i32', named(L.SURFACE_FORMS), 'B-spline surface forms, as the pools hold them.'),
    ...consts('transition', 'i32', named(L.TRANSITIONS), 'Composite curve transitions, as the pools hold them.'),
    ...consts('trim_preference', 'i32', named(L.TRIM_PREFERENCES), 'Trimmed curves\' master representations.'),
  ]);
}

export function analysisRustText(): string {
  return rustModule('Analysis', 'cad-brep analysis buffer', { magic: A.ANALYSIS_MAGIC, columns: ANALYSIS_COLUMNS,
    headerBytes: ANALYSIS_HEADER_BYTES }, [
    '//! cad_analysis.rs: a cad-brep analysis buffer (what is derived from one model buffer, tied to it by the',
    '//! model\'s SHA-256) for Rust readers. Generated by packages/cad-brep/gen/rust.ts from',
    '//! packages/cad-brep/src/analysis-layout.ts, which documents every table and column; don\'t edit. The format is',
    '//! cad_brep.rs\'s; `Analysis::open` copies the buffer and checks its header, and each column is then a slice of',
    '//! its type, by a method named for its table and column (`edge_range`). A per-entity table (vertex, edge,',
    '//! coedge, face, surface, shell) is empty or has the model\'s rows; checking that, and the hash, is the',
    '//! caller\'s.',
  ], [
    ...consts('provenance', 'u8', A.PROVENANCE, 'Where a value came from (`edge_range_from`, ...).'),
    ...consts('measure_trust', 'u8', A.MEASURE_TRUST, 'How far a measure is to be trusted (`face_area_from`).'),
    ...consts('continuity', 'u8', A.CONTINUITY, 'Continuity across an edge (`continuity_class`).'),
    ...consts('singularity', 'u8', A.SINGULARITY, 'Singularity kinds, as the first real of each record in '
      + '`pool_real` (compare `x as u8`).'),
    ...consts('facing', 'u8', A.FACING, 'Which way a shell\'s faces face (`shell_facing`).'),
    ...consts('facing_from', 'u8', A.FACING_FROM, 'How a shell\'s facing was found (`shell_facing_from`).'),
    ...consts('logical', 'u8', L.LOGICAL, 'Three-valued logicals (`surface_u_closed`, `surface_v_closed`).'),
  ]);
}

if (import.meta.main) {
  for (const [file, text] of [['cad_brep.rs', rustText()], ['cad_analysis.rs', analysisRustText()]] as const) {
    const path = new URL(`../include/${file}`, import.meta.url);
    writeFileSync(path, text);
    console.log(`wrote ${path.pathname}`);
  }
}
