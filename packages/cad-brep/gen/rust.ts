// Writes include/cad_brep.rs from src/layout.ts: `node packages/cad-brep/gen/rust.ts`. A test checks the committed
// module is current, and compiles a reader against it.

import { writeFileSync } from 'node:fs';
import { COLUMNS, HEADER_BYTES } from '../src/data.ts';
import * as L from '../src/layout.ts';

const snake = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const RUST_TYPES = { u8: 'u8', i32: 'i32', u32: 'u32', f64: 'f64' } as const;
const LETTERS = { u8: 'b', i32: 'i', u32: 'u', f64: 'f' } as const;

/** Text word-wrapped to lines of at most 120 characters, each starting with `lead`. */
function wrap(text: string, lead: string): string[] {
  const lines: string[] = [];
  let line = lead;
  for (const w of text.split(/\s+/)) {
    if (line.length + 1 + w.length > 120 && line.trim() !== lead.trim()) {
      lines.push(line);
      line = lead;
    }
    line += (line === lead ? '' : ' ') + w;
  }
  lines.push(line);
  return lines;
}

/** A module of constants, `type` their type. */
function consts(name: string, type: string, table: Record<string, number>, doc: string): string[] {
  return [`/// ${doc}`, `pub mod ${name} {`,
    ...Object.entries(table).map(([k, v]) => `    pub const ${snake(k).toUpperCase()}: ${type} = ${v};`), '}', ''];
}

const named = (names: readonly string[]) => Object.fromEntries(names.map((n, k) => [n, k]));

function layouts(title: string, table: Record<string, { reals: string; ints: string }>): string[] {
  const out = wrap(`${title}, from a row's real and int offsets into its table's pools:`, '//! ');
  for (const [kind, l] of Object.entries(table)) {
    out.push(...wrap(`${kind}: reals ${l.reals || 'none'}; ints ${l.ints || 'none'}.`, '//!   '));
  }
  return out;
}

export function rustText(): string {
  const out = [
    '//! cad_brep.rs: a cad-brep buffer (one part\'s B-rep) for Rust readers. Generated by',
    '//! packages/cad-brep/gen/rust.ts from packages/cad-brep/src/layout.ts, which documents every table and column;',
    '//! don\'t edit. The buffer: the magic, a u32 column count, then per column its byte offset and element count',
    '//! (u32 each), then the columns, each 8-byte aligned. Little-endian. `Brep::open` copies the buffer (so it',
    '//! needn\'t be aligned) and checks its header; each column is then a slice of its type, by a method named for',
    '//! its table and column (`edge_curve`).',
    '//!',
    ...layouts('Curves (d the row\'s dim; a placement 9 reals in 3D: origin, axis, x direction; 4 in 2D: origin, x '
      + 'direction)', L.CURVE_LAYOUTS),
    '//!',
    ...layouts('Surfaces (a placement 9 reals)', L.SURFACE_LAYOUTS),
    '',
    '#![allow(dead_code)]',
    '',
    '#[cfg(not(target_endian = "little"))]',
    'compile_error!("cad-brep buffers are little-endian");',
    '',
    `pub const MAGIC: &[u8; 4] = b"${L.MAGIC}";`,
    `pub const HEADER_BYTES: usize = ${HEADER_BYTES};`,
    `pub const COLUMN_COUNT: usize = ${COLUMNS.length};`,
    '',
    '/// Each column\'s element type, in buffer order: b u8, i i32, u u32, f f64.',
    `const TYPES: &[u8; COLUMN_COUNT] = b"${COLUMNS.map((c) => LETTERS[c.type]).join('')}";`,
    '',
    'const fn bytes(k: usize) -> usize {',
    '    match TYPES[k] {',
    '        b\'b\' => 1,',
    '        b\'f\' => 8,',
    '        _ => 4,',
    '    }',
    '}',
    '',
    ...consts('curve_kind', 'u8', L.CURVE_KIND, 'Curve kinds (`curve_kind`).'),
    ...consts('surface_kind', 'u8', L.SURFACE_KIND, 'Surface kinds (`surface_kind`).'),
    ...consts('logical', 'i32', L.LOGICAL, 'Three-valued logicals, as the pools hold them.'),
    ...consts('edge_flags', 'u8', L.EDGE_FLAGS, 'Edge flags (`edge_flags`), bits.'),
    ...consts('orientation', 'u8', L.ORIENTATION, 'Coedge orientations (`coedge_orientation`).'),
    ...consts('loop_kind', 'u8', L.LOOP_KIND, 'Loop kinds (`loop_kind`).'),
    ...consts('bound', 'u8', L.BOUND, 'Loop bounds (`loop_bound`).'),
    ...consts('shell_kind', 'u8', L.SHELL_KIND, 'Shell kinds (`shell_kind`).'),
    ...consts('body_kind', 'u8', L.BODY_KIND, 'Body kinds (`body_kind`).'),
    ...consts('item_kind', 'u8', L.ITEM_KIND, 'Item kinds (`item_kind`).'),
    ...consts('curve_form', 'i32', named(L.CURVE_FORMS), 'B-spline curve forms, as the pools hold them.'),
    ...consts('surface_form', 'i32', named(L.SURFACE_FORMS), 'B-spline surface forms, as the pools hold them.'),
    ...consts('transition', 'i32', named(L.TRANSITIONS), 'Composite curve transitions, as the pools hold them.'),
    ...consts('trim_preference', 'i32', named(L.TRIM_PREFERENCES), 'Trimmed curves\' master representations.'),
    '/// A buffer\'s columns: a copy of it in 8-byte words, and each column\'s byte offset and element count.',
    'pub struct Brep {',
    '    words: Vec<u64>,',
    '    columns: [(usize, usize); COLUMN_COUNT],',
    '}',
    '',
    'impl Brep {',
    '    /// The columns of a buffer, or why it isn\'t one (the magic, the column count, a column that doesn\'t fit).',
    '    pub fn open(buf: &[u8]) -> Result<Brep, String> {',
    '        let u32_at = |k: usize| u32::from_le_bytes([buf[k], buf[k + 1], buf[k + 2], buf[k + 3]]) as usize;',
    '        if buf.len() < HEADER_BYTES || &buf[0..4] != MAGIC {',
    '            return Err(format!("not a cad-brep buffer of this format ({})", String::from_utf8_lossy(MAGIC)));',
    '        }',
    '        if u32_at(4) != COLUMN_COUNT {',
    '            return Err(format!("{} columns, not {COLUMN_COUNT}", u32_at(4)));',
    '        }',
    '        let mut columns = [(0, 0); COLUMN_COUNT];',
    '        for (k, c) in columns.iter_mut().enumerate() {',
    '            let (offset, count) = (u32_at(8 + 8 * k), u32_at(12 + 8 * k));',
    '            if offset % 8 != 0 || offset < HEADER_BYTES || offset > buf.len()',
    '                || count.checked_mul(bytes(k)).map_or(true, |n| n > buf.len() - offset)',
    '            {',
    '                return Err(format!("column {k}: {count} values at byte {offset} don\'t fit"));',
    '            }',
    '            *c = (offset, count);',
    '        }',
    '        let mut words = vec![0u64; buf.len().div_ceil(8)];',
    '        for (w, chunk) in words.iter_mut().zip(buf.chunks(8)) {',
    '            let mut b = [0u8; 8];',
    '            b[..chunk.len()].copy_from_slice(chunk);',
    '            *w = u64::from_le_bytes(b);',
    '        }',
    '        Ok(Brep { words, columns })',
    '    }',
    '',
    '    fn slice<T>(&self, k: usize) -> &[T] {',
    '        let (offset, count) = self.columns[k];',
    '        // (Sound: the words are 8-byte aligned, every column starts on an 8-byte offset and fits, checked by',
    '        // `open`, and every bit pattern is a value of these types.)',
    '        unsafe { std::slice::from_raw_parts((self.words.as_ptr() as *const u8).add(offset) as *const T, count) }',
    '    }',
    '',
    '    /// Any column\'s values as f64 (for readers that walk every column).',
    '    pub fn values(&self, k: usize) -> Vec<f64> {',
    '        match TYPES[k] {',
    '            b\'b\' => self.slice::<u8>(k).iter().map(|&x| x as f64).collect(),',
    '            b\'i\' => self.slice::<i32>(k).iter().map(|&x| x as f64).collect(),',
    '            b\'u\' => self.slice::<u32>(k).iter().map(|&x| x as f64).collect(),',
    '            _ => self.slice::<f64>(k).to_vec(),',
    '        }',
    '    }',
    ...COLUMNS.flatMap((c, k) => ['', `    /// \`${c.table}.${c.column}\`: ${c.width} per row.`,
      `    pub fn ${snake(c.table)}_${snake(c.column)}(&self) -> &[${RUST_TYPES[c.type]}] { self.slice(${k}) }`]),
    '}',
    '',
  ];
  return out.join('\n');
}

if (import.meta.main) {
  const path = new URL('../include/cad_brep.rs', import.meta.url);
  writeFileSync(path, rustText());
  console.log(`wrote ${path.pathname}`);
}
