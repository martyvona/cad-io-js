import fs from 'node:fs';
import { createRequire } from 'node:module';
import { indexP21, closure, emitSubset, typeOf, hasType, attrText } from './p21.mjs';
const require = createRequire(import.meta.url);
const [orig, root, scale] = process.argv.slice(2);
const idx = indexP21(fs.readFileSync(orig));
const R = +root, e = idx.ents.get(R);
console.log('#' + R, typeOf(e), 'items:', e.refs.map((r) => '#' + r + ' ' + typeOf(idx.ents.get(r))).join(', '));
let b = idx.order.reduce((a, x) => Math.max(a, x), 0) + 1; const id = () => '#' + b++;
const [ac, pc, p_, pdf, pdc, pd, pds, sdr] = Array.from({ length: 8 }, id);
const sub = emitSubset(idx, closure(idx, [R]), [`${ac}=APPLICATION_CONTEXT('');`, `${pc}=PRODUCT_CONTEXT('',${ac},'mechanical');`, `${p_}=PRODUCT('part','part','',(${pc}));`, `${pdf}=PRODUCT_DEFINITION_FORMATION('','',${p_});`, `${pdc}=PRODUCT_DEFINITION_CONTEXT('part definition',${ac},'design');`, `${pd}=PRODUCT_DEFINITION('design','',${pdf},${pdc});`, `${pds}=PRODUCT_DEFINITION_SHAPE('','',${pd});`, `${sdr}=SHAPE_DEFINITION_REPRESENTATION(${pds},#${R});`]);
fs.writeFileSync(`out_${R}.stp`, sub);
const occt = await require('occt-import-js')();
const r = occt.ReadStepFile(sub, { linearDeflectionType: 'absolute_value', linearDeflection: 0.05 });
console.log('meshes', r.meshes.length, r.meshes.map((m) => m.brep_faces.length).join(','));
const faces = [];
const walk = (id) => { const x = idx.ents.get(id); const t = typeOf(x); if (/FACE_SURFACE|ADVANCED_FACE/.test(t)) return faces.push(id); if (/SHELL|BREP|SURFACE_MODEL|SHAPE_REPRESENTATION/.test(t)) x.refs.forEach(walk); };
walk(R);
const pt = (id) => { const m = /\(([^()]*)\)\s*$/.exec(attrText(idx, idx.ents.get(id))); return m[1].split(',').map(Number); };
const occF = r.meshes.flatMap((m, mi) => m.brep_faces.map((bf) => { const p = m.attributes.position.array, ix = m.index.array; const vs = []; for (let t = bf.first; t <= bf.last; t++) for (let v = 0; v < 3; v++) { const q = ix[3 * t + v] * 3; vs.push([p[q], p[q + 1], p[q + 2]]); } return vs; }));
const map = faces.map((fid) => {
  const f = idx.ents.get(fid);
  const vps = [...closure(idx, f.refs.slice(0, -1))].map((id) => idx.ents.get(id)).filter((e) => hasType(e, 'VERTEX_POINT')).map((e) => pt(e.refs[0]).map((x) => x * scale));
  if (!vps.length) return 'nov';
  let best = -1, bd = Infinity;
  occF.forEach((vs, j) => { const d = Math.max(...vps.map((q) => Math.min(...vs.map((v) => Math.hypot(v[0] - q[0], v[1] - q[1], v[2] - q[2]))))); if (d < bd) { bd = d; best = j; } });
  return bd < 1e-3 ? best : `${best}?${bd.toExponential(0)}`;
});
console.log('step faces', faces.length, 'occt faces', occF.length);
console.log(map.join(' '));
